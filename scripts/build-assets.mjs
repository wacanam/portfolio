import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');
const publicDir = path.join(rootDir, 'public');
const genDir = path.join(rootDir, 'src', 'generated');

async function main() {
  console.log('[build-assets] Starting asset optimization pipeline...');
  await fs.mkdir(publicDir, { recursive: true });
  await fs.mkdir(genDir, { recursive: true });

  const siteUrl = (process.env.VITE_SITE_URL || 'https://waveambray.dev').replace(/\/+$/, '');
  const basePath = (process.env.VITE_BASE_PATH || '/').replace(/\/?$/, '/');

  // 1. Resolve source portrait
  const portraitPrimary = path.join(rootDir, '23647.jpg');
  const portraitSecondary = path.join(publicDir, 'profile.jpg');
  let sourcePortraitPath = null;

  try {
    await fs.access(portraitPrimary);
    sourcePortraitPath = portraitPrimary;
  } catch {
    try {
      await fs.access(portraitSecondary);
      sourcePortraitPath = portraitSecondary;
    } catch {
      console.warn('[build-assets] Source portrait not found. Generating fallback geometric avatar...');
    }
  }

  let sourceBuffer;
  if (sourcePortraitPath) {
    sourceBuffer = await fs.readFile(sourcePortraitPath);
  } else {
    sourceBuffer = Buffer.from(`
      <svg width="1024" height="1024" viewBox="0 0 1024 1024" xmlns="http://www.w3.org/2000/svg">
        <rect width="1024" height="1024" fill="#0D0F14"/>
        <circle cx="512" cy="420" r="180" fill="#2A2D35"/>
        <path d="M256 920 C256 680, 768 680, 768 920 Z" fill="#2A2D35"/>
      </svg>
    `);
  }

  // 2. Head-and-shoulders crop (778x778 at top:0, left:123 from 1024x1024)
  const meta = await sharp(sourceBuffer).metadata();
  const width = meta.width || 1024;
  const height = meta.height || 1024;
  const cropSize = Math.round(Math.min(width, height) * 0.76); // 778px for 1024x1024
  const cropLeft = Math.round((width - cropSize) / 2); // 123px
  const cropTop = 0; // Preserves full 42px studio headroom, terminates at y=778 (147px clear above ID badge)

  const cropped = sharp(sourceBuffer).extract({
    left: cropLeft,
    top: cropTop,
    width: cropSize,
    height: cropSize
  });

  console.log(`[build-assets] Cropped portrait: ${cropSize}x${cropSize} at top:${cropTop}, left:${cropLeft}`);

  // 3. Multi-format portrait outputs
  await cropped.clone().resize(400, 400).webp({ quality: 80 }).toFile(path.join(publicDir, 'profile-400.webp'));
  await cropped.clone().resize(400, 400).avif({ quality: 75 }).toFile(path.join(publicDir, 'profile-400.avif'));
  await cropped.clone().resize(800, 800).webp({ quality: 82 }).toFile(path.join(publicDir, 'profile-800.webp'));
  await cropped.clone().resize(800, 800).avif({ quality: 78 }).toFile(path.join(publicDir, 'profile-800.avif'));

  // 4. 24px base64 blur placeholder
  const blurBuffer = await cropped.clone().resize(24, 24).webp({ quality: 30 }).toBuffer();
  const blurDataUri = `data:image/webp;base64,${blurBuffer.toString('base64')}`;

  const assetMetaContent = `// Auto-generated by scripts/build-assets.mjs - DO NOT EDIT MANUALLY
const base = import.meta.env.BASE_URL;

export const profileMeta = {
  width: ${cropSize},
  height: ${cropSize},
  aspectRatio: 1,
  blurDataUri: '${blurDataUri}',
  src400Webp: \`\${base}profile-400.webp\`,
  src400Avif: \`\${base}profile-400.avif\`,
  src800Webp: \`\${base}profile-800.webp\`,
  src800Avif: \`\${base}profile-800.avif\`,
} as const;

export const profileBlurDataUri = profileMeta.blurDataUri;
`;
  await fs.writeFile(path.join(genDir, 'assetMeta.ts'), assetMetaContent, 'utf-8');
  console.log('[build-assets] Wrote src/generated/assetMeta.ts with 24px blur placeholder');

  // 5. Favicon squircle SVG and PNG icons
  const faviconSvg = `<svg width="512" height="512" viewBox="0 0 512 512" xmlns="http://www.w3.org/2000/svg">
  <defs>
    <linearGradient id="goldGrad" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0%" stop-color="#FFFFFF"/>
      <stop offset="100%" stop-color="#D6C5A9"/>
    </linearGradient>
  </defs>
  <rect width="512" height="512" rx="115" fill="#050507"/>
  <rect width="508" height="508" x="2" y="2" rx="113" fill="none" stroke="#D6C5A9" stroke-width="4" stroke-opacity="0.35"/>
  <path d="M120 160 L188 352 L256 224 L324 352 L392 160" fill="none" stroke="url(#goldGrad)" stroke-width="42" stroke-linecap="round" stroke-linejoin="round"/>
</svg>`;
  await fs.writeFile(path.join(publicDir, 'favicon.svg'), faviconSvg, 'utf-8');

  const faviconBuf = Buffer.from(faviconSvg);
  await sharp(faviconBuf).resize(180, 180).png().toFile(path.join(publicDir, 'apple-touch-icon.png'));
  await sharp(faviconBuf).resize(192, 192).png().toFile(path.join(publicDir, 'icon-192.png'));
  await sharp(faviconBuf).resize(512, 512).png().toFile(path.join(publicDir, 'icon-512.png'));
  console.log('[build-assets] Generated favicon.svg and PNG icons (180, 192, 512)');

  // 6. Keynote 1200x630 OpenGraph card
  const ogWidth = 1200;
  const ogHeight = 630;
  const portraitSize = 360;
  const circleMask = Buffer.from(`<svg width="${portraitSize}" height="${portraitSize}"><circle cx="${portraitSize / 2}" cy="${portraitSize / 2}" r="${portraitSize / 2}" fill="#fff"/></svg>`);

  const maskedPortrait = await cropped
    .clone()
    .resize(portraitSize, portraitSize)
    .composite([{ input: circleMask, blend: 'dest-in' }])
    .png()
    .toBuffer();

  // 48 golden-spiral orbital micro-dots (strictly NO connecting lines)
  let dotsSvg = '';
  const dotCount = 48;
  const centerX = 930;
  const centerY = 315;
  for (let i = 0; i < dotCount; i++) {
    const angle = i * 0.45;
    const r = 210 + i * 2.5;
    const x = centerX + r * Math.cos(angle);
    const y = centerY + r * Math.sin(angle);
    const dotR = 1.2 + (i % 3) * 0.6;
    const opacity = (0.2 + (i / dotCount) * 0.5).toFixed(2);
    dotsSvg += `<circle cx="${x.toFixed(1)}" cy="${y.toFixed(1)}" r="${dotR}" fill="#D6C5A9" opacity="${opacity}"/>`;
  }

  const ogSvg = `
<svg width="${ogWidth}" height="${ogHeight}" viewBox="0 0 ${ogWidth} ${ogHeight}" xmlns="http://www.w3.org/2000/svg">
  <defs>
    <radialGradient id="bgGlow" cx="75%" cy="50%" r="60%">
      <stop offset="0%" stop-color="#D6C5A9" stop-opacity="0.12"/>
      <stop offset="50%" stop-color="#14161A" stop-opacity="0.05"/>
      <stop offset="100%" stop-color="#050507" stop-opacity="0"/>
    </radialGradient>
    <linearGradient id="titaniumGrad" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0%" stop-color="#FFFFFF"/>
      <stop offset="100%" stop-color="#D6C5A9"/>
    </linearGradient>
  </defs>

  <rect width="${ogWidth}" height="${ogHeight}" fill="url(#bgGlow)"/>
  ${dotsSvg}

  <!-- Status pill -->
  <circle cx="86" cy="96" r="5" fill="#10B981"/>
  <circle cx="86" cy="96" r="9" fill="#10B981" opacity="0.25"/>
  <text x="108" y="101" font-family="monospace, -apple-system" font-size="14" font-weight="600" letter-spacing="2" fill="#10B981">AVAILABLE FOR REMOTE ROLES</text>

  <!-- Headline -->
  <text x="80" y="215" font-family="-apple-system, BlinkMacSystemFont, 'SF Pro Display', 'Inter', sans-serif" font-size="72" font-weight="700" letter-spacing="-2.5" fill="url(#titaniumGrad)">Wave C. Ambray</text>

  <!-- Subtitle -->
  <text x="82" y="280" font-family="-apple-system, BlinkMacSystemFont, 'SF Pro Display', 'Inter', sans-serif" font-size="30" font-weight="500" letter-spacing="-0.5" fill="#D6C5A9">Full-Stack Software Engineer</text>

  <!-- Monospace proof strip -->
  <rect x="80" y="460" width="580" height="1" fill="rgba(255, 255, 255, 0.08)"/>
  <text x="80" y="510" font-family="monospace" font-size="16" font-weight="600" letter-spacing="1.5" fill="#86868B">
    <tspan fill="#F5F5F7">6+ YRS</tspan>  ·  <tspan fill="#F5F5F7">100M+ SPATIAL POINTS</tspan>  ·  <tspan fill="#D6C5A9">C# / .NET &amp; TYPESCRIPT</tspan>
  </text>

  <!-- Portrait Frame Ring -->
  <circle cx="${centerX}" cy="${centerY}" r="182" fill="none" stroke="#D6C5A9" stroke-width="1.5" stroke-opacity="0.35"/>
</svg>`;

  const ogCard = await sharp({
    create: {
      width: ogWidth,
      height: ogHeight,
      channels: 4,
      background: '#050507'
    }
  })
    .composite([
      { input: Buffer.from(ogSvg), top: 0, left: 0 },
      { input: maskedPortrait, top: Math.round(centerY - portraitSize / 2), left: Math.round(centerX - portraitSize / 2) }
    ])
    .png()
    .toBuffer();

  await fs.writeFile(path.join(publicDir, 'og-image.png'), ogCard);
  await sharp(ogCard).webp({ quality: 90 }).toFile(path.join(publicDir, 'og-image.webp'));
  console.log('[build-assets] Generated public/og-image.png and public/og-image.webp (1200x630)');

  // 7. PWA manifest, robots.txt, sitemap.xml
  const webmanifest = {
    name: 'Wave C. Ambray — Full-Stack Software Engineer',
    short_name: 'Wave Ambray',
    description: 'Portfolio of Wave C. Ambray, Full-Stack & Backend Software Engineer specializing in distributed .NET & TypeScript architectures.',
    start_url: basePath,
    display: 'standalone',
    background_color: '#050507',
    theme_color: '#050507',
    icons: [
      { src: `${basePath}icon-192.png`, sizes: '192x192', type: 'image/png' },
      { src: `${basePath}icon-512.png`, sizes: '512x512', type: 'image/png' }
    ]
  };
  await fs.writeFile(path.join(publicDir, 'site.webmanifest'), JSON.stringify(webmanifest, null, 2), 'utf-8');

  const robots = `User-agent: *\nAllow: /\n\nSitemap: ${siteUrl}/sitemap.xml\n`;
  await fs.writeFile(path.join(publicDir, 'robots.txt'), robots, 'utf-8');

  const today = new Date().toISOString().split('T')[0];
  const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
  <url>
    <loc>${siteUrl}/</loc>
    <lastmod>${today}</lastmod>
    <changefreq>monthly</changefreq>
    <priority>1.0</priority>
  </url>
</urlset>\n`;
  await fs.writeFile(path.join(publicDir, 'sitemap.xml'), sitemap, 'utf-8');

  console.log('[build-assets] Asset pipeline successfully completed.');
}

main().catch(err => {
  console.error('[build-assets] Error running asset pipeline:', err);
  process.exit(1);
});
